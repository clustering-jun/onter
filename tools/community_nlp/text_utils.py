def _completion_names_sub(m):
    """'수료(보고)(이름[,이름])'의 괄호 안 이름을 가린다. 괄호 안이 이름이 아닌 일반어(전문가 등)면 그대로 둔다."""
    names = re.split(r"\s*[,，·]\s*", m.group("n").strip())
    if any(n in _NOT_NAME for n in names):
        return m.group(0)
    return (m.group("g") or "") + m.group("o") + "[이름]" + m.group("c")


