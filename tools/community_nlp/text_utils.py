def compact(s):
    """NFKC·소문자·공백/문장부호 제거 (숫자는 유지)."""
    s = unicodedata.normalize("NFKC", "" if s is None else str(s)).lower()
    return _PUNCT.sub("", s)


def mask_for_match(nc):
    """유형 판정용: 사업 포장어·보고 접미를 가린 명칭."""
    return _MASK_FOR_MATCH.sub("", nc)


def umbrella_tags(nc):
    return [name for name, rx in UMBRELLAS if rx.search(nc)]


def has_household_identifier(*texts):
    """식별 패턴(동·호수·부분 가림 이름 등)이 남아 있는지 점검한다. 마스킹이 끝난 텍스트에 쓰면 '잔여 패턴' 점검이 된다."""
    return any(bool(_SENS_DETECT.search(unicodedata.normalize("NFKC", str(t or "")))) for t in texts)


def was_masked(*texts):
    """마스킹이 원문을 실제로 바꿨는지(=식별 패턴이 있어 가려졌는지). sensitive_identifier_flag의 정의."""
    return any(mask_sensitive(t) != unicodedata.normalize("NFKC", "" if t is None else str(t)) for t in texts)


def mask_sensitive(s):
    s = unicodedata.normalize("NFKC", "" if s is None else str(s))
    for rx, rep in _SENS_PATTERNS:
        s = rx.sub(rep, s)
    return s


_GENERIC_SUFFIX = re.compile(
    r"(실시|시행|진행|개최|추진|완료|보고서|보고|결과|소식|참여|운영|활동|행사|사업|프로그램|서비스|지원|제공|연계|안내|홍보)+$")
_COMPLEX_TAIL = re.compile(r"\d+단지(내)?")


def title_norm(name, complex_name=""):
    """같은 사업의 반복 기록 묶기용 제목: 연·월·차수·단지명·실시류를 제거."""
    s = unicodedata.normalize("NFKC", "" if name is None else str(name)).lower()
    cn = compact(complex_name)
    s = re.sub(r"(20)?\d{2}\s*년도?", "", s)
    s = re.sub(r"`\s*\d{2}|’\s*\d{2}", "", s)
    s = re.sub(r"\d{1,2}\s*[~\-]\s*\d{1,2}\s*월", "", s)
    s = re.sub(r"\d{1,2}\s*월(\s*[~\-]\s*\d{1,2}\s*월)?", "", s)
    s = re.sub(r"(제\s*)?\d+\s*(차수|차|회차|회|기|호|분기)", "", s)
    s = re.sub(r"(상|하)반기|[1-4]\s*분기|동계|하계", "", s)
    s = re.sub(r"\d{4,8}", "", s)  # 8자리 날짜 등
    s = _PUNCT.sub("", s)
    if cn:
        s = s.replace(cn, "")
        s = s.replace(re.sub(r"\d+$", "", cn), "")
    s = _COMPLEX_TAIL.sub("", s)
    s = re.sub(r"\d+", "", s)
    prev = None
    while prev != s:
        prev = s
        s = _GENERIC_SUFFIX.sub("", s)
    return s or compact(name)
